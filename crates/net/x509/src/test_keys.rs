//! The register of RSA key pairs the test certificates are signed with.
//!
//! It is `pub` behind `test-certificates` because two crates build
//! certificates from it: this one and `audhsos-tls`, whose state machine
//! is driven against a server whose chain is RSA. Copying half a kibibyte
//! of key material into a second crate's test sources to keep it private
//! would say less and be harder to check.
//!
//! No project code generates an RSA key. Generation needs random primes
//! and a primality test, which would be the largest piece of arithmetic
//! in the track and would serve test data alone; signing with a key that
//! is already known needs only the exponentiation verification already
//! has. So these two pairs were made once, outside this repository, with
//!
//! ```text
//! openssl genrsa 2048
//! openssl genrsa 4096
//! ```
//!
//! and their modulus and private exponent are transcribed below. The
//! public exponent of both is sixty-five thousand five hundred and
//! thirty-seven. This is the one place where a number this project did
//! not compute enters its tests, and D-83 states it as such: every
//! certificate is still built and signed by project code, and
//! `crypto-ec` generates nothing either.

