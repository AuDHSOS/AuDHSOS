#[test]
fn a_block_with_a_table_of_its_own_reads_back() {
    let mut out = vec![0u8; SENTENCE.len()];
    let read = decompress(&DYNAMIC, &mut out).expect("the stream reads");
    assert_eq!(out.get(..read), Some(SENTENCE));
}

#[test]
fn a_block_that_carries_its_bytes_reads_back() {
    let mut out = vec![0u8; SENTENCE.len()];
    let read = decompress(&STORED, &mut out).expect("the stream reads");
    assert_eq!(out.get(..read), Some(SENTENCE));
}

#[test]
fn a_zlib_stream_from_elsewhere_reads_back() {
    let mut out = vec![0u8; SENTENCE.len()];
    let read = decompress_zlib(&ZLIB, &mut out).expect("the stream reads");
    assert_eq!(out.get(..read), Some(SENTENCE));
}

#[test]
fn the_sentence_is_the_one_the_streams_were_made_from() {
    assert_eq!(SENTENCE.len(), 354);
    assert_eq!(crate::adler32(SENTENCE), 0x0001_7fea);
}
