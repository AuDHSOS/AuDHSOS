/// Regression for issue #49: every message length from zero past the
/// first block, where the padding run wraps into the next block, against
/// digests taken from an independent implementation.
#[test]
fn every_length_past_the_first_block_hashes_as_documented() {
    for (length, expected) in DIGESTS_512.iter().enumerate() {
        let message = vec![b'a'; length];
        assert_eq!(hex(&Sha512::digest(&message)), *expected, "length {length}");
    }
    for (length, expected) in DIGESTS_384.iter().enumerate() {
        let message = vec![b'a'; length];
        assert_eq!(hex(&Sha384::digest(&message)), *expected, "length {length}");
    }
}
