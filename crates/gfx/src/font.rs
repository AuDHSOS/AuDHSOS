//! The project's own bitmap font.
//!
//! Ninety-five glyphs, one for every printable character of ASCII, each
//! eight pixels wide and sixteen tall, one bit per pixel, the leftmost
//! pixel in the highest bit of a row. The shapes are five by seven inside
//! that cell, at column one and row four, which leaves a column of space on
//! the left, two on the right, and room below the baseline for the tails of
//! `g`, `j`, `p`, `q`, and `y`. Nothing outside this repository was used to
//! make them.
//!
//! Invariants: the table holds exactly [`GLYPH_COUNT`] glyphs, in the order
//! of the characters they draw; a character the table has no glyph for
//! draws [`REPLACEMENT`], so text of any content renders.

