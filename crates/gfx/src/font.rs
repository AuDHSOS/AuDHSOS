/// The glyph of `character`, or [`REPLACEMENT`] when the table has none.
#[must_use]
pub fn glyph(character: char) -> &'static [u8; 16] {
    let index = u32::from(character).checked_sub(u32::from(FIRST_GLYPH));
    let slot = index
        .and_then(|offset| usize::try_from(offset).ok())
        .and_then(|offset| GLYPHS.get(offset));
    match slot {
        Some(rows) => rows,
        None => &REPLACEMENT,
    }
}

/// Draws `text` at `x`, `y` in `foreground`, and the cell around each glyph
/// in `background` when there is one, and answers with the part of the
/// surface it wrote. Characters that would stand past the right edge of the
/// surface are clipped away, and the text is one row of cells: it does not
/// wrap.
pub fn draw_text(
    surface: &mut Surface<'_>,
    x: u32,
    y: u32,
    text: &str,
    foreground: Color,
    background: Option<Color>,
) -> Rect {
    let mut cell_x = x;
    let mut written = Rect::EMPTY;
    for character in text.chars() {
        let cell = Rect::new(cell_x, y, GLYPH_WIDTH, GLYPH_HEIGHT)
            .clip_to(surface.width(), surface.height());
        if let Some(color) = background {
            surface.fill(cell, color);
        }
        written = written.union(draw_glyph(surface, cell_x, y, glyph(character), foreground));
        written = written.union(cell);
        cell_x = cell_x.saturating_add(GLYPH_WIDTH);
    }
    written
}

/// Draws one glyph and answers with the part of the surface it wrote.
fn draw_glyph(surface: &mut Surface<'_>, x: u32, y: u32, rows: &[u8; 16], color: Color) -> Rect {
    let mut written = Rect::EMPTY;
    for (row, bits) in rows.iter().enumerate() {
        let offset = u32::try_from(row).unwrap_or(0);
        for column in 0..GLYPH_WIDTH {
            let mask = 1_u8.checked_shl(GLYPH_WIDTH.saturating_sub(1).saturating_sub(column));
            let set = mask.is_some_and(|bit| bits & bit != 0);
            let pixel_x = x.saturating_add(column);
            let pixel_y = y.saturating_add(offset);
            if set && surface.set_pixel(pixel_x, pixel_y, color) {
                written = written.union(Rect::new(pixel_x, pixel_y, 1, 1));
            }
        }
    }
    surface.add_damage(written);
    written
}
